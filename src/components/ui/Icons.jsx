function OutlineIcon({ d, strokeWidth = 2, ...props }) {
    return (
        <svg fill="none" stroke="currentColor" viewBox="0 0 24 24" {...props}>
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={strokeWidth} d={d} />
        </svg>
    );
}

function SolidIcon({ children, viewBox = '0 0 20 20', ...props }) {
    return (
        <svg fill="currentColor" viewBox={viewBox} {...props}>
            {children}
        </svg>
    );
}

